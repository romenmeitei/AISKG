def validate_additional_expected_results(
    outcome_graph: Mapping[str, Any],
    temporal_normalized: Mapping[str, pd.DataFrame],
    sensitivity: Mapping[str, pd.DataFrame],
    concentration: Mapping[str, pd.DataFrame],
    output_dir: Path,
) -> pd.DataFrame:
    checks: List[Dict[str, Any]] = []
    def add(name: str, actual: Any, expected: Any, tolerance: float = 0.0) -> None:
        if isinstance(expected, float):
            passed = bool(np.isfinite(float(actual)) and abs(float(actual) - expected) <= tolerance)
        else:
            passed = actual == expected
        checks.append({"check": name, "actual": actual, "expected": expected, "tolerance": tolerance, "status": "PASS" if passed else "FAIL"})

    out_sum = outcome_graph["summary"].iloc[0]
    add("Outcome-aware aggregated relations", int(out_sum["aggregated_typed_relations"]), 170)
    add("Outcome-aware support>=2 relations", int(out_sum["evidence_filtered_relations_support_ge_2"]), 77)
    add("Outcome-aware active nodes", int(out_sum["active_nodes"]), 38)
    add("Outcome-aware active edges", int(out_sum["active_directed_edges"]), 77)
    add("Outcome-aware communities", int(out_sum["communities"]), 5)
    add("Outcome-aware outcome outgoing edges", int(out_sum["outcome_outgoing_edges"]), 0)
    add("Outcome-aware modularity", float(out_sum["weighted_Louvain_modularity"]), 0.3303953959134851, 1e-12)

    temp = temporal_normalized["normalized"].set_index("period")
    add("Temporal normalized 2000-2009 eligible publications", int(temp.loc["2000–2009", "eligible_publications"]), 476)
    add("Temporal normalized 2020-2025 eligible publications", int(temp.loc["2020–2025", "eligible_publications"]), 711)
    add("Temporal normalized 2020-2025 edges per 100 publications", float(temp.loc["2020–2025", "edges_per_100_eligible_publications"]), 14.767932489451477, 1e-12)
    add("Temporal rarefaction iterations", int(temporal_normalized["rarefaction_summary"].iloc[0]["iterations"]), TEMPORAL_RAREFACTION_ITERATIONS)

    mc = sensitivity["monte_carlo_summary"]
    c20 = mc[(mc["weight_family"] == "dirichlet_c20") & (mc["toxin_class"] == "Virotoxins")].iloc[0]
    add("Composite sensitivity iterations per family", int(sensitivity["monte_carlo_iterations"]["iteration"].nunique()), COMPOSITE_SENSITIVITY_ITERATIONS)
    add("Virotoxins dirichlet_c20 top-3 probability", float(c20["probability_top_3_priority"]), 1.0, 1e-12)

