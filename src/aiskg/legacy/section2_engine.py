def _compute_representation_scores(frame: pd.DataFrame, weights: Mapping[str, float], transform: str = "minmax") -> pd.DataFrame:
    source_map = {
        "publication_component": "unique_publications",
        "mention_component": "entity_mentions",
        "sentence_component": "unique_sentences",
        "edge_component": "incident_edges",
        "neighbor_component": "unique_neighbor_concepts",
        "centrality_component": "weighted_degree",
    }
    out = frame.copy()
    for component, source in source_map.items():
        values = pd.to_numeric(out[source], errors="coerce").fillna(0).astype(float)
        if transform == "log1p_minmax":
            values = np.log1p(values)
            out[component] = minmax(pd.Series(values, index=out.index))
        elif transform == "percentile_rank":
            out[component] = values.rank(pct=True, method="average")
        else:
            out[component] = minmax(values)
    total_weight = sum(float(w) for w in weights.values())
    if total_weight <= 0:
        raise ValueError("Composite-score weights must sum to a positive value.")
    norm_weights = {k: float(v) / total_weight for k, v in weights.items()}
    out["Composite_Representation_Score_sensitivity"] = sum(out[k] * norm_weights[k] for k in norm_weights)
    out["Underrepresentation_Score_sensitivity"] = 1 - out["Composite_Representation_Score_sensitivity"]
    out["Integrated_Research_Priority_Score_sensitivity"] = out["Underrepresentation_Score_sensitivity"] * np.where(out["unique_publications"] > 0, 1.0, 0.5)
    out = out.sort_values(["Integrated_Research_Priority_Score_sensitivity", "Underrepresentation_Score_sensitivity"], ascending=False).reset_index(drop=True)
    out["priority_rank_sensitivity"] = np.arange(1, len(out) + 1)
    return out


def run_composite_score_sensitivity_analysis(toxin_representation: pd.DataFrame, output_dir: Path) -> Dict[str, pd.DataFrame]:
    components = ["publication_component", "mention_component", "sentence_component", "edge_component", "neighbor_component", "centrality_component"]
    baseline_weights = {
        "publication_component": 0.35,
        "mention_component": 0.15,
        "sentence_component": 0.10,
        "edge_component": 0.15,
        "neighbor_component": 0.10,
        "centrality_component": 0.15,
    }
    scenarios = {
        "baseline": baseline_weights,
        "equal_weights": {c: 1 / len(components) for c in components},
        "literature_volume_emphasis": {"publication_component": 0.45, "mention_component": 0.20, "sentence_component": 0.15, "edge_component": 0.08, "neighbor_component": 0.06, "centrality_component": 0.06},
        "network_integration_emphasis": {"publication_component": 0.15, "mention_component": 0.08, "sentence_component": 0.07, "edge_component": 0.30, "neighbor_component": 0.20, "centrality_component": 0.20},
    }
    for omitted in components:
        weights = {c: baseline_weights[c] for c in components if c != omitted}
        total = sum(weights.values())
        scenarios[f"leave_out_{omitted}"] = {c: w / total for c, w in weights.items()}

    scenario_rows = []
    for scenario, weights in scenarios.items():
        scored = _compute_representation_scores(toxin_representation, weights, transform="minmax")
        for _, row in scored.iterrows():
            scenario_rows.append({
                "scenario": scenario,
                "toxin_class": row["toxin_class"],
                "composite_score": row["Composite_Representation_Score_sensitivity"],
                "priority_score": row["Integrated_Research_Priority_Score_sensitivity"],
                "priority_rank": int(row["priority_rank_sensitivity"]),
            })
    scenario_df = pd.DataFrame(scenario_rows)

    norm_rows = []
    for transform in ["minmax", "log1p_minmax", "percentile_rank"]:
        scored = _compute_representation_scores(toxin_representation, baseline_weights, transform=transform)
        for _, row in scored.iterrows():
            norm_rows.append({
                "normalization": transform,
                "toxin_class": row["toxin_class"],
                "composite_score": row["Composite_Representation_Score_sensitivity"],
                "priority_score": row["Integrated_Research_Priority_Score_sensitivity"],
                "priority_rank": int(row["priority_rank_sensitivity"]),
            })
    norm_df = pd.DataFrame(norm_rows)

    rng = np.random.default_rng(RANDOM_SEED + 210)
    base_alpha = np.array([baseline_weights[c] for c in components], dtype=float)
    base_scored = _compute_representation_scores(toxin_representation, baseline_weights)
    class_order = base_scored["toxin_class"].tolist()
    base_rank = base_scored.set_index("toxin_class")["priority_rank_sensitivity"].astype(int).to_dict()
    component_matrix = base_scored[components].to_numpy(dtype=float)
    mc_frames = []
    summary_rows = []
    n_classes = len(class_order)
    iteration_index = np.arange(COMPOSITE_SENSITIVITY_ITERATIONS)
    for family, concentration in [("dirichlet_c100", 100), ("dirichlet_c20", 20), ("dirichlet_unrestricted", None)]:
        alpha = base_alpha * concentration if concentration is not None else np.ones(len(components))
        sampled_weights = rng.dirichlet(alpha, size=COMPOSITE_SENSITIVITY_ITERATIONS)  # iterations x components
        scores = component_matrix @ sampled_weights.T  # classes x iterations; lower score = higher underrepresentation priority
        orders = np.argsort(scores, axis=0, kind="mergesort")
        ranks = np.empty_like(orders)
        ranks[orders, np.arange(COMPOSITE_SENSITIVITY_ITERATIONS)] = np.arange(1, n_classes + 1)[:, None]
        records = []
        for class_index, toxin_class in enumerate(class_order):
            class_ranks = ranks[class_index, :].astype(int)
            records.append(pd.DataFrame({
                "weight_family": family,
                "iteration": iteration_index,
                "toxin_class": toxin_class,
                "priority_rank": class_ranks,
            }))
            summary_rows.append({
                "weight_family": family,
                "toxin_class": toxin_class,
                "baseline_rank": int(base_rank[toxin_class]),
                "median_rank": float(np.median(class_ranks)),
                "rank_ci_low": float(np.percentile(class_ranks, 2.5)),
                "rank_ci_high": float(np.percentile(class_ranks, 97.5)),
                "probability_top_3_priority": float(np.mean(class_ranks <= 3)),
                "probability_same_rank_as_baseline": float(np.mean(class_ranks == base_rank[toxin_class])),
                "probability_same_priority_tier_as_baseline": float(np.mean([_priority_tier_from_rank(r, n_classes) == _priority_tier_from_rank(base_rank[toxin_class], n_classes) for r in class_ranks])),
            })
        mc_frames.append(pd.concat(records, ignore_index=True))
    mc = pd.concat(mc_frames, ignore_index=True)
    mc.to_csv(output_dir / "12_composite_score_monte_carlo_iterations.csv", index=False)
    mc_summary = pd.DataFrame(summary_rows).sort_values(["weight_family", "baseline_rank", "toxin_class"]).reset_index(drop=True)
    scenario_df.to_csv(output_dir / "12_composite_score_sensitivity_scenarios.csv", index=False)
    norm_df.to_csv(output_dir / "12_composite_score_normalization_sensitivity.csv", index=False)
    mc_summary.to_csv(output_dir / "12_composite_score_monte_carlo_summary.csv", index=False)

    fig, ax = plt.subplots(figsize=(10, 6))
    plot = mc_summary[mc_summary["weight_family"] == "dirichlet_c20"].sort_values("baseline_rank")
    ax.errorbar(plot["median_rank"], plot["toxin_class"], xerr=[plot["median_rank"] - plot["rank_ci_low"], plot["rank_ci_high"] - plot["median_rank"]], fmt="o")
    ax.invert_xaxis()
    ax.set_xlabel("Priority rank (lower number = higher priority)")
    ax.set_ylabel("Toxin class")
    ax.set_title("Composite-score sensitivity under broad weight perturbation")
    fig.tight_layout()
    fig.savefig(output_dir / "12_composite_score_sensitivity_rank_intervals.png", dpi=300, bbox_inches="tight")
    plt.close(fig)
    return {"scenarios": scenario_df, "normalization": norm_df, "monte_carlo_summary": mc_summary, "monte_carlo_iterations": mc}


def _priority_tier_from_rank(rank: int, total: int) -> str:
    p = rank / max(total, 1)
    return "Very high" if p <= .20 else "High" if p <= .40 else "Moderate" if p <= .70 else "Lower"


def run_toxin_concentration_recalculation(input_dir: Path, output_dir: Path) -> Dict[str, pd.DataFrame]:
    entities = pd.read_csv(input_dir / "01_document_sentence_entities.csv", low_memory=False)
    work = entities.copy()
    work["_document"] = work["document_id"].fillna("").astype(str).str.strip()
    work["_sentence"] = work["sentence_id"].fillna("").astype(str).str.strip()
    work["_surface"] = work["matched_text"].fillna("").astype(str).str.strip()
    work["_class"] = work["entity_type"].fillna("").astype(str).str.upper().str.strip()
    work["_canonical"] = work["canonical_entity"].fillna("").astype(str).str.strip()
    work["_preferred_term"] = np.where(work["_canonical"].ne(""), work["_canonical"], work["_surface"])
    work["toxin_class"] = work["_preferred_term"].map(classify_toxin)
    missing = work["toxin_class"].isna()
    work.loc[missing, "toxin_class"] = work.loc[missing, "_surface"].map(classify_toxin)
    toxin_entities = work[(work["_class"].isin({"TOXIN", "MUSHROOM_TOXIN", "CHEMICAL_TOXIN"}) | work["toxin_class"].notna()) & work["toxin_class"].notna()].copy()
    toxin_entities = toxin_entities.drop_duplicates(["_document", "_sentence", "_surface", "toxin_class"])
    doc_pairs = toxin_entities[["toxin_class", "_document"]].drop_duplicates()
    classes = sorted(doc_pairs["toxin_class"].unique())
    doc_to_classes = doc_pairs.groupby("_document")["toxin_class"].apply(lambda s: sorted(set(s))).to_dict()
    total_docs = len(doc_to_classes)
    assignment_counts = doc_pairs.groupby("toxin_class")["_document"].nunique().reindex(classes).fillna(0).astype(float)
    assignment_shares = assignment_counts / assignment_counts.sum()

    fractional_counts = pd.Series(0.0, index=classes)
    multilabel_distribution = Counter()
    for doc, class_list in doc_to_classes.items():
        multilabel_distribution[len(class_list)] += 1
        share = 1.0 / len(class_list)
        for cls in class_list:
            fractional_counts.loc[cls] += share
    fractional_shares = fractional_counts / total_docs

    def _hhi_entropy(shares: pd.Series) -> Tuple[float, float]:
        values = shares.astype(float).to_numpy()
        hhi = float(np.sum(values ** 2))
        values = values[values > 0]
        entropy = float(-np.sum(values * np.log(values)))
        norm_entropy = float(entropy / math.log(len(values))) if len(values) > 1 else np.nan
        return hhi, norm_entropy
    hhi_assignment, ent_assignment = _hhi_entropy(assignment_shares)
    hhi_fractional, ent_fractional = _hhi_entropy(fractional_shares)

    rng = np.random.default_rng(RANDOM_SEED + 310)
    documents = np.array(sorted(doc_to_classes))
    class_to_index = {cls: i for i, cls in enumerate(classes)}
    frac_matrix = np.zeros((len(documents), len(classes)), dtype=float)
    for row_index, doc in enumerate(documents):
        cls_list = doc_to_classes[doc]
        increment = 1.0 / len(cls_list)
        for cls in cls_list:
            frac_matrix[row_index, class_to_index[cls]] = increment
    boot_hhi: List[float] = []
    boot_entropy: List[float] = []
    batch_size = 500
    for start in range(0, BOOTSTRAP_ITERATIONS, batch_size):
        batch_n = min(batch_size, BOOTSTRAP_ITERATIONS - start)
        sampled_indices = rng.integers(0, len(documents), size=(batch_n, len(documents)))
        sampled_shares = frac_matrix[sampled_indices].mean(axis=1)
        boot_hhi.extend(np.sum(sampled_shares ** 2, axis=1).tolist())
        with np.errstate(divide="ignore", invalid="ignore"):
            terms = np.where(sampled_shares > 0, sampled_shares * np.log(sampled_shares), 0.0)
        boot_entropy.extend((-np.sum(terms, axis=1) / math.log(len(classes))).tolist())
